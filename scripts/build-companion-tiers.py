"""Build reduced-resolution copies of the companion atlases + the TS index that picks them.

Why: a 500px atlas cell drawn at ~125px (4x minification) shimmers while it rotates, because
animated layers are resampled without mipmaps. Measured (2026-11-07, scripts/probe-companion-rig.py):
the shimmer disappears when a cell is at most ~1.5x the displayed device pixels.
Tiers: 500 (original) / 340 / 230 / 160 px cells. Resizing uses premultiplied alpha (no dark fringe).
Usage: py -3 scripts/build-companion-tiers.py   (run after scripts/build-companion-atlas.py)
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src' / 'assets' / 'companion'
OUT_TS = ROOT / 'src' / 'components' / 'companionSheets.ts'
FULL_CELL = 500
TIERS = {340: 'm', 230: 's', 160: 'xs'}
NAMES = ['body-mint', 'body-pearl', 'body-rose', 'head-mint', 'head-pearl', 'head-rose',
         'front-mint', 'front-pearl', 'front-rose', 'eyes', 'mouth']


def ident(name, suffix):
    a, _, b = name.partition('-')
    return a + (b.capitalize() if b else '') + (suffix.capitalize() if suffix else '')


def main():
    for name in NAMES:
        im = Image.open(SRC / f'{name}.webp').convert('RGBA')
        assert im.size == (FULL_CELL * 3, FULL_CELL * 3), (name, im.size)
        pm = im.convert('RGBa')
        for cell, suffix in TIERS.items():
            small = pm.resize((cell * 3, cell * 3), Image.LANCZOS).convert('RGBA')
            small.save(SRC / f'{name}.{suffix}.webp', 'WEBP', quality=90, alpha_quality=95, method=6)
    lines = ['// Generated by scripts/build-companion-tiers.py — do not edit by hand.']
    tiers = [(FULL_CELL, '')] + list(TIERS.items())
    for cell, suffix in tiers:
        for name in NAMES:
            file = f'{name}.webp' if not suffix else f'{name}.{suffix}.webp'
            lines.append(f"import {ident(name, suffix)} from '../assets/companion/{file}';")
    lines.append('')
    lines.append('export interface CompanionSheetTier { cell: number; body: Record<string, string>; head: Record<string, string>; front: Record<string, string>; eyes: string; mouth: string }')
    lines.append('/** Largest first. Pick the smallest tier whose cell still covers the drawn size. */')
    lines.append('export const COMPANION_SHEET_TIERS: CompanionSheetTier[] = [')
    for cell, suffix in tiers:
        t = lambda part: '{ ' + ', '.join(f'{tone}: {ident(part + "-" + tone, suffix)}' for tone in ('mint', 'pearl', 'rose')) + ' }'
        lines.append(f"  {{ cell: {cell}, body: {t('body')}, head: {t('head')}, front: {t('front')}, eyes: {ident('eyes', suffix)}, mouth: {ident('mouth', suffix)} }},")
    lines.append('];')
    OUT_TS.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    total = sum(p.stat().st_size for p in SRC.glob('*.webp'))
    print(f'{OUT_TS.relative_to(ROOT)}; companion assets total {total // 1024} KB')


if __name__ == '__main__':
    main()
